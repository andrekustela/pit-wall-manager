// O formato é aproximado: a ideia é reconhecer o jeitão de cada pista.
// Código do traçado: S = reta (m), R/L = curva à direita/esquerda (graus/raio m),
// R0/raio = última curva, completa o giro sozinha.
import type { TrackDef } from "./track";
import { turtle } from "./trackShape";

interface Extra {
  /** altura mínima (1..11): pista ondulada = alto */
  h: number;
  /** equilíbrio ideal (asa dianteira - traseira) */
  b: number;
  /** chance de chuva (0..1) */
  rain: number;
  street?: boolean;
  ov?: number;
  fig8?: boolean;
  grass?: [string, string];
}

const GREEN: [string, string] = ["#3d8a3a", "#418f3d"];
const DRY: [string, string] = ["#7e8a3e", "#849042"];
const DESERT: [string, string] = ["#b89a62", "#bea067"];
const CITY: [string, string] = ["#6f7177", "#73757b"];

function P(name: string, blurb: string, shape: string, x: Extra): TrackDef {
  const grass = x.grass ?? (x.street ? CITY : GREEN);
  return {
    name,
    blurb,
    minHeight: x.h,
    balance: x.b,
    rainChance: x.rain,
    grass,
    street: x.street,
    overtake: x.ov ?? (x.street ? 0.6 : 1),
    ...turtle(shape, { figure8: x.fig8 }),
  };
}

